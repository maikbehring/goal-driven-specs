#!/usr/bin/env node
/**
 * Embeds docs/specs/*.md into docs/specs/specs-data.js for view.html (file:// safe).
 * Run from project root: node scripts/build-spec-viewer.mjs
 * npm script: "specs:html": "node scripts/build-spec-viewer.mjs"
 */
import fs from 'fs';
import path from 'path';

const root = process.cwd();
const specsDir = path.join(root, 'docs', 'specs');
const outFile = path.join(specsDir, 'specs-data.js');

if (!fs.existsSync(specsDir)) {
  console.error(`Missing ${specsDir} (run from project root)`);
  process.exit(1);
}

const files = fs
  .readdirSync(specsDir)
  .filter((f) => f.endsWith('.md'))
  .sort((a, b) => a.localeCompare(b, 'en'));

const entries = {};
for (const file of files) {
  entries[file] = fs.readFileSync(path.join(specsDir, file), 'utf8');
}

const banner = `/* Auto-generated by scripts/build-spec-viewer.mjs — do not edit */\n`;
fs.writeFileSync(
  outFile,
  banner + `window.SPEC_DOCS = ${JSON.stringify(entries, null, 2)};\n`,
  'utf8'
);
console.log(`Wrote ${outFile} (${files.length} files)`);
